/**
 * The stability of one feature.
 * @param {string} id - Feature ID
 * @returns {'experimental'|'stable'|undefined} undefined for an ID the registry does not hold
 */
export function featureStability(id) {
    return Object.hasOwn(FEATURES, id) ? FEATURES[id] : undefined
}

/**
 * Every feature and its stability, ordered by ID.
 * @returns {Array<{id: string, stability: 'experimental'|'stable'}>}
 */
export function listFeatures() {
    return Object.keys(FEATURES).sort().map((id) => ({ id, stability: FEATURES[id] }))
}
