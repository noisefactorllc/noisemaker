/**
 * Stability registry.
 *
 * FEATURES is the only place that states a feature's stability. A feature is
 * `experimental` or `stable`. An experimental feature is complete and works by
 * default; its names, defaults, argument shapes and rendered output are outside
 * the stability guarantee.
 *
 * SURFACE is where each part of the engine names the feature it belongs to. No
 * part states a stability: it names a feature ID, and FEATURES says what that
 * feature's stability is. Changing a value in FEATURES is the whole of
 * graduating a feature; the documentation that depends on it is generated by
 * shaders/scripts/generate-stability-docs.mjs.
 *
 * This module imports nothing.
 */

